const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('desk', {
  loadState: () => ipcRenderer.invoke('state:load'),
  saveState: (s) => ipcRenderer.invoke('state:save', s),
  saveStateNow: (s) => ipcRenderer.sendSync('state:save-sync', s),
  ytTitle: (id) => ipcRenderer.invoke('yt:title', id),
  shots: {
    capture: () => ipcRenderer.invoke('shot:capture'),
    list: () => ipcRenderer.invoke('shot:list'),
    info: () => ipcRenderer.invoke('shot:info'),
    remove: (f) => ipcRenderer.invoke('shot:delete', f),
    reveal: (f) => ipcRenderer.invoke('shot:reveal', f),
    copy: (f) => ipcRenderer.invoke('shot:copy', f),
    drag: (f) => ipcRenderer.send('shot:drag', f),
    onNew: (fn) => ipcRenderer.on('shot:new', (_e, it) => fn(it)),
    onError: (fn) => ipcRenderer.on('shot:error', (_e, m) => fn(m)),
  },
  backupState: (tag) => ipcRenderer.invoke('state:backup', tag),
  info: () => ipcRenderer.invoke('app:info'),
  changelog: () => ipcRenderer.invoke('app:changelog'),
  applySettings: (s) => ipcRenderer.invoke('settings:apply', s),
  update: {
    check: () => ipcRenderer.invoke('upd:check'),
    download: () => ipcRenderer.invoke('upd:download'),
    install: () => ipcRenderer.invoke('upd:install'),
    onProgress: (fn) => { const f = (_e, p) => fn(p); ipcRenderer.on('upd:progress', f); return () => ipcRenderer.removeListener('upd:progress', f); },
  },
  pick: (kind) => ipcRenderer.invoke('dialog:pick', kind),
  pickMedia: () => ipcRenderer.invoke('media:pick'),
  pickImage: () => ipcRenderer.invoke('photo:pick'),
  memory: () => ipcRenderer.invoke('app:memory'),
  iptv: {
    load: (src, refresh) => ipcRenderer.invoke('iptv:load', src, refresh),
    forget: (src) => ipcRenderer.invoke('iptv:forget', src),
    pick: () => ipcRenderer.invoke('iptv:pick'),
    headers: (url, h) => ipcRenderer.invoke('iptv:headers', url, h),
    probe: (url) => ipcRenderer.invoke('iptv:probe', url),
  },
  describe: (p) => ipcRenderer.invoke('fav:describe', p),
  installedApps: (refresh) => ipcRenderer.invoke('apps:list', refresh),
  iconFor: (p) => ipcRenderer.invoke('fav:icon', p),
  pickIcon: () => ipcRenderer.invoke('icon:pick'),
  launch: (item) => ipcRenderer.invoke('fav:launch', item),
  pathForFile: (file) => webUtils.getPathForFile(file),
  places: () => ipcRenderer.invoke('fs:places'),
  list: (dir) => ipcRenderer.invoke('fs:list', dir),
  watchDir: (id, dir) => ipcRenderer.invoke('fs:watch', id, dir),
  unwatchDir: (id) => ipcRenderer.invoke('fs:unwatch', id),
  onDirChanged: (cb) => ipcRenderer.on('fs:changed', (_e, id, dir) => cb(id, dir)),
  read: (p) => ipcRenderer.invoke('fs:read', p),
  write: (p, t) => ipcRenderer.invoke('fs:write', p, t),
  open: (p) => ipcRenderer.invoke('fs:open', p),
  reveal: (p) => ipcRenderer.invoke('fs:reveal', p),
  mkdir: (dir, name) => ipcRenderer.invoke('fs:mkdir', dir, name),
  newFile: (dir, name) => ipcRenderer.invoke('fs:newfile', dir, name),
  rename: (from, name) => ipcRenderer.invoke('fs:rename', from, name),
  trash: (p) => ipcRenderer.invoke('fs:trash', p),
  paste: (items, dir, cut) => ipcRenderer.invoke('fs:paste', items, dir, cut),
  copyText: (text) => ipcRenderer.invoke('clip:write', text),
  readText: () => ipcRenderer.invoke('clip:read'),
  pageSource: (partition, url) => ipcRenderer.invoke('br:source', partition, url),
  onViewSource: (cb) => ipcRenderer.on('web:viewsource', (_e, id) => cb(id)),
  hist: {
    add: (pr, url, title) => ipcRenderer.invoke('hist:add', pr, url, title),
    title: (pr, url, title) => ipcRenderer.invoke('hist:title', pr, url, title),
    list: (pr, q, limit) => ipcRenderer.invoke('hist:list', pr, q, limit),
    remove: (pr, ids) => ipcRenderer.invoke('hist:remove', pr, ids),
    clear: (pr) => ipcRenderer.invoke('hist:clear', pr),
  },
  editCmd: (cmd) => ipcRenderer.invoke('edit:cmd', cmd),
  notePath: (id) => ipcRenderer.invoke('notes:path', id),
  notesList: () => ipcRenderer.invoke('notes:list'),
  siteCookies: (partition, url) => ipcRenderer.invoke('br:site-cookies', partition, url),
  clearSite: (partition, url, withData) => ipcRenderer.invoke('br:clear-site', partition, url, withData),
  pw: {
    accounts: (profile, url) => ipcRenderer.invoke('pw:accounts', profile, url),
    fill: (profile, url, id) => ipcRenderer.invoke('pw:fill', profile, url, id),
    check: (profile, url, u, p) => ipcRenderer.invoke('pw:check', profile, url, u, p),
    save: (profile, url, u, p, id) => ipcRenderer.invoke('pw:save', profile, url, u, p, id),
    never: (profile, url) => ipcRenderer.invoke('pw:never', profile, url),
    unNever: (profile, origin) => ipcRenderer.invoke('pw:unnever', profile, origin),
    list: (profile) => ipcRenderer.invoke('pw:list', profile),
    remove: (id) => ipcRenderer.invoke('pw:remove', id),
    edit: (id, u, p) => ipcRenderer.invoke('pw:edit', id, u, p),
    setMaster: (n, o) => ipcRenderer.invoke('pw:set-master', n, o),
    unlock: (p) => ipcRenderer.invoke('pw:unlock', p),
    unlocked: () => ipcRenderer.invoke('pw:unlocked'),
    reveal: (id) => ipcRenderer.invoke('pw:reveal', id),
    importCsv: (profile) => ipcRenderer.invoke('pw:import', profile),
  },
  clearBrowserProfile: (name) => ipcRenderer.invoke('br:clear-profile', name),
  showWindow: () => ipcRenderer.invoke('win:reveal'),
  dock: (where) => ipcRenderer.invoke('win:dock', where),
  native: {
    browsers: () => ipcRenderer.invoke('native:browsers'),
    attach: (id, spec) => ipcRenderer.invoke('native:attach', id, spec),
    windows: () => ipcRenderer.invoke('native:windows'),
    bounds: (id, rect, visible) => ipcRenderer.invoke('native:bounds', id, rect, visible),
    release: (id, close) => ipcRenderer.invoke('native:release', id, close),
    suspend: (on) => ipcRenderer.invoke('native:suspend', on),
    focus: (id) => ipcRenderer.invoke('native:focus', id),
    onGone: (fn) => ipcRenderer.on('native:gone', (_e, id) => fn(id)),
    onSpawn: (fn) => ipcRenderer.on('native:spawn', (_e, id, w) => fn(id, w)),
    onTitle: (fn) => ipcRenderer.on('native:title', (_e, id, t) => fn(id, t)),
  },
  onWebCtx: (fn) => ipcRenderer.on('web:ctx', (_e, wcId, p) => fn(wcId, p)),
  onWebLink: (fn) => ipcRenderer.on('web:link', (_e, wcId, url, mode) => fn(wcId, url, mode)),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  platform: process.platform,
});
